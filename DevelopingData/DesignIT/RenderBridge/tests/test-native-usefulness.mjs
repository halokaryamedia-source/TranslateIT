import fs from 'node:fs';
import path from 'node:path';

const bridge = process.env.TRANSLATEIT_RENDER_BRIDGE || 'http://127.0.0.1:8844';
const targetUrl = process.argv[2] || 'https://www.mivubi.com/';
const reportDir = path.join(process.cwd(), 'reports');
fs.mkdirSync(reportDir, { recursive: true });
async function readJson(res) { const text = await res.text(); let payload = {}; try { payload = text ? JSON.parse(text) : {}; } catch {} if (!res.ok) throw new Error('HTTP ' + res.status + ': ' + (payload.error || text)); return payload; }
const health = await readJson(await fetch(bridge + '/health'));
const payload = await readJson(await fetch(bridge + '/render?url=' + encodeURIComponent(targetUrl)));
const model = payload.cloneModel || {};
const layers = model.layers || [];
const diagnostics = payload.diagnostics || {};
const native = diagnostics.nativeUsefulness || {};
const textLayers = layers.filter((x) => x.type === 'text' || x.type === 'button').length;
const imageLayers = layers.filter((x) => x.type === 'image').length;
const shapeLayers = layers.filter((x) => x.type === 'shape').length;
const failures = [];
const warnings = [];
if (health.activeRenderer !== 'plugin/code-native-editable.js') failures.push('active renderer is not native editable');
if (health.rendererMode !== 'native-editable-reconstruction-primary') failures.push('renderer mode is not native editable primary');
if (native.extractor !== 'dom-faithful-native-v1') failures.push('DOM-faithful native extractor is not active');
if (layers.length < 55) failures.push(`too few native layers: ${layers.length}`);
if (textLayers < 25) failures.push(`too few editable text/button layers: ${textLayers}`);
if (imageLayers < 2) warnings.push(`low image layer count: ${imageLayers}`);
if (shapeLayers < 8) warnings.push(`low surface/background layer count: ${shapeLayers}`);
if ((native.coverageRatio || 0) < 0.18) warnings.push(`low raw DOM coverage ratio: ${native.coverageRatio}`);
const generic = layers.filter((x) => /^layer-|raw-|Element$|Layer$/i.test(String(x.name || ''))).length;
if (generic) failures.push(`${generic} generic layer names remain`);
const report = { gate: 'translateit-native-usefulness', status: failures.length ? 'fail' : 'pass', targetUrl, activeRenderer: health.activeRenderer, rendererMode: health.rendererMode, extractor: native.extractor || null, rawElements: native.rawElements || 0, keptElements: native.keptElements || 0, coverageRatio: native.coverageRatio || 0, layers: layers.length, textLayers, imageLayers, shapeLayers, sections: (model.sections || []).length, genericLayerNames: generic, failures, warnings };
fs.writeFileSync(path.join(reportDir, 'translateit-native-usefulness.json'), JSON.stringify(report, null, 2), 'utf8');
console.log(JSON.stringify(report, null, 2));
if (failures.length) process.exitCode = 2;
